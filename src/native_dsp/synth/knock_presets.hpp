// Only the values that differ from the defaults, in table order.
consteval std::size_t change_count(const Kit& kit) {
  const auto values = kit_values(kit);
  std::size_t count = 0;
  for (std::size_t i = 0; i < parameter_count; ++i) {
    count += values[i] != parameters[i].default_value ? 1U : 0U;
  }
  return count;
}

template <const Kit& K> consteval std::array<V, change_count(K)> changes() {
  std::array<V, change_count(K)> out{};
  const auto values = kit_values(K);
  std::size_t j = 0;
  for (std::size_t i = 0; i < parameter_count; ++i) {
    if (values[i] != parameters[i].default_value) {
      out[j++] = V{parameters[i].id, values[i]};
    }
  }
  return out;
}

