#!/usr/bin/env python3
"""Regenerate cmake/TestBudgets.cmake from ctest JUnit reports.

Run the tests on an otherwise idle machine, as the project runs them, then
pass the reports and the build tree they came from:

    ctest --preset quick -j4 --output-junit junit.xml
    scripts/update-test-budgets.py --test-dir build/quick build/quick/junit.xml

A measured test's budget is three times its slowest time across the reports,
rounded up and never below its tier's default (OSCILLATE_TEST_DEFAULT_BUDGET_*
in cmake/ProjectOptions.cmake). The table holds only what the defaults do not
cover: every slow and live test, which must have a measured budget, and fast
tests that need more than the fast default. Tests absent from the reports keep
their current entry, so a partial run (one label, one test) updates only those.
An entry is dropped when its test is neither configured in any --test-dir nor
named in any CMakeLists.txt, so pass every build tree whose feature set adds
tests (fuzz, live, VST3, codec) when pruning.
"""

import argparse
import json
import math
import pathlib
import re
import subprocess
import xml.etree.ElementTree as ElementTree

ROOT = pathlib.Path(__file__).resolve().parent.parent
TABLE = ROOT / "cmake" / "TestBudgets.cmake"
OPTIONS = ROOT / "cmake" / "ProjectOptions.cmake"
FACTOR = 3.0
TIERS = ("fast", "slow", "live")
ENTRY = re.compile(r"^set\(OSCILLATE_TEST_BUDGET_(\S+) (\d+)\)$")
DEFAULT = re.compile(r"^set\(OSCILLATE_TEST_DEFAULT_BUDGET_(\w+) (\d+)\)$", re.MULTILINE)
HEADER = """\
# Generated by scripts/update-test-budgets.py from a `ctest -j4` run: three
# times each test's measured time, never below its tier's default
# (OSCILLATE_TEST_DEFAULT_BUDGET_* in ProjectOptions.cmake). Every slow and
# live test is listed; a fast test only when it needs more than the fast
# default. A test that needs longer is too slow or hung; fix the test, then
# regenerate.
"""


def tier_defaults():
    defaults = {tier: int(seconds) for tier, seconds in DEFAULT.findall(OPTIONS.read_text())}
    missing = [tier for tier in TIERS if tier not in defaults]
    if missing:
        raise SystemExit(f"{OPTIONS.relative_to(ROOT)} has no default budget for {missing}")
    return defaults


def read_table():
    budgets = {}
    if TABLE.exists():
        for line in TABLE.read_text().splitlines():
            match = ENTRY.match(line)
            if match:
                budgets[match.group(1)] = int(match.group(2))
    return budgets


def configured_tiers(test_dir):
    listing = subprocess.run(
        ["ctest", "--test-dir", str(test_dir), "--show-only=json-v1"],
        check=True, capture_output=True, text=True).stdout
    tiers = {}
    for test in json.loads(listing)["tests"]:
        labels = []
        for prop in test.get("properties", []):
            if prop["name"] == "LABELS":
                labels = prop["value"]
        tier = next((label for label in labels if label in TIERS), None)
        if tier:
            tiers[test["name"]] = tier
    return tiers


def cmake_words():
    words = set()
    for path in ROOT.rglob("CMakeLists.txt"):
        if "build" in path.relative_to(ROOT).parts[:1]:
            continue
        words.update(re.findall(r"[A-Za-z0-9_.]+", path.read_text()))
    return words


def named_in_cmake(name, words):
    # A case test `<contract>.<case>` names both parts in its CMakeLists.
    return all(part in words for part in name.split("."))


def measured(report):
    for case in ElementTree.parse(report).getroot().iter("testcase"):
        if case.get("status", "run") != "run" or case.find("failure") is not None:
            continue
        if case.find("skipped") is not None:
            continue
        yield case.get("name"), float(case.get("time", "0"))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--test-dir", action="append", type=pathlib.Path, required=True,
                        help="configured build tree; repeat for each feature set")
    parser.add_argument("reports", nargs="*", type=pathlib.Path)
    arguments = parser.parse_args()
    defaults = tier_defaults()
    tiers = {}
    for test_dir in arguments.test_dir:
        tiers.update(configured_tiers(test_dir))
    budgets = read_table()
    slowest = {}
    for report in arguments.reports:
        for name, seconds in measured(report):
            slowest[name] = max(seconds, slowest.get(name, 0.0))
    for name, seconds in slowest.items():
        # A test no --test-dir configures has no known tier: keep its old entry.
        if name not in tiers:
            continue
        floor = defaults[tiers[name]]
        budgets[name] = max(floor, math.ceil(seconds * FACTOR))

    words = cmake_words()
    kept = {}
    dropped = []
    unmeasured = []
    for name, budget in budgets.items():
        tier = tiers.get(name)
        if tier is None and not named_in_cmake(name, words):
            dropped.append(name)
            continue
        if tier == "fast" and budget <= defaults["fast"]:
            continue
        if tier in ("slow", "live"):
            budget = max(budget, defaults[tier])
        kept[name] = budget
    for name, tier in tiers.items():
        if tier != "fast" and name not in kept:
            unmeasured.append(name)

    lines = [HEADER] + [
        f"set(OSCILLATE_TEST_BUDGET_{name} {kept[name]})" for name in sorted(kept)
    ]
    TABLE.write_text("\n".join(lines) + "\n")
    print(f"{len(slowest)} budgets measured, {len(kept)} in {TABLE.relative_to(ROOT)}")
    if dropped:
        print(f"dropped {len(dropped)} entries for tests that no longer exist: "
              + ", ".join(sorted(dropped)))
    if unmeasured:
        raise SystemExit("slow or live tests without a budget (run them and pass the report): "
                         + ", ".join(sorted(unmeasured)))


if __name__ == "__main__":
    main()
